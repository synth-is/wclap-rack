#!/usr/bin/env bash
# Regenerate src/faust_templates/: one C++ class per Faust template of the platform
# (kromosynth/faust-templates/*.dsp), so a FaustNode in a genome's patch runs natively in the engine.
# The generated headers are kept in the tree; scripts/build.sh does not need Faust.
# Needs the Faust compiler (default ~/faust/bin/faust; override FAUST=...) and the templates
# (default ~/Developer/apps/synth.is/kromosynth/faust-templates; override TEMPLATES=...).
# Usage: engines/cppn-engine/scripts/gen-faust-templates.sh
set -euo pipefail
HERE="$(cd "$(dirname "$0")/.." && pwd)"
FAUST="${FAUST:-$HOME/faust/bin/faust}"
TEMPLATES="${TEMPLATES:-$HOME/Developer/apps/synth.is/kromosynth/faust-templates}"
OUT="$HERE/src/faust_templates"
rm -rf "$OUT" && mkdir -p "$OUT"
ALL="$OUT/all.h"
{
  echo "// GENERATED by scripts/gen-faust-templates.sh with $("$FAUST" --version | head -1). Do not edit."
  echo "// Included by faust_nodes.h inside namespace fdsp."
} > "$ALL"
FACTORY=""
for f in "$TEMPLATES"/*.dsp; do
  n="$(basename "$f" .dsp)"
  c="T_$(echo "$n" | tr - _)"
  # -os -ec: one frame() per sample, and the slider-dependent work in control(), which the engine
  # calls once per 128 frames (as the worklet reads its parameters)
  "$FAUST" -lang cpp -single -os -ec -cn "$c" -scn FaustDsp "$f" -o "$OUT/$n.h"
  echo "#include \"$n.h\"  // sha256 of the .dsp: $(shasum -a 256 "$f" | cut -c1-16)" >> "$ALL"
  FACTORY="$FACTORY  if (name == \"$n\") return new $c();"$'\n'
done
{
  echo "inline FaustDsp* createTemplate(const std::string& name) {"
  printf "%s" "$FACTORY"
  echo "  return nullptr;"
  echo "}"
} >> "$ALL"
echo "generated $(ls "$OUT" | wc -l | tr -d ' ') files in $OUT"
