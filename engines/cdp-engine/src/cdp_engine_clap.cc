// Called by the host (between process calls) when an async render has completed.
// `planar` was malloc'd by the host in this module's memory; ownership passes to the voice.
extern "C" void cdp_deliver(uint32_t reqId, float* planar, uint32_t frames, uint32_t chans, double rate,
                            int32_t baseKey) {
  CdpEngine* s = g_current;
  if (!s || !planar || frames < 2 || chans < 1) {
    if (planar) std::free(planar);
    return;
  }
  Voice* v = nullptr;
  for (auto& cand : s->voices)
    if (cand.active && cand.reqId == reqId && !cand.hasBuffer) { v = &cand; break; }
  if (!v) {  // note already gone (choked/reset): drop the buffer
    std::free(planar);
    return;
  }
  freeVoiceBuffer(*v);
  v->buf = planar;
  v->frames = frames;
  v->chans = chans;
  v->rate = rate > 0 ? rate : s->sampleRate;
  v->baseKey = baseKey;
  v->step = v->rate / s->sampleRate * std::pow(2.0, (v->key - baseKey) / 12.0);
  v->pos = 0;
  v->hasBuffer = true;
  if (v->released) {  // note-off arrived while rendering: start the release immediately
    v->stage = 2;
    const uint32_t dur = (uint32_t)std::max(1.0, kReleaseSec * s->sampleRate);
    v->stageLeft = dur;
    v->stageStep = -v->env / (double)dur;
  } else {
    v->stage = 0;
    const uint32_t dur = (uint32_t)std::max(1.0, kAttackSec * s->sampleRate);
    v->stageLeft = dur;
    v->stageStep = 1.0 / (double)dur;
  }
  std::printf("cdp-engine: delivered req=%u note=%d frames=%u ch=%u rate=%.0f baseKey=%d\n", reqId, v->key, frames,
              chans, v->rate, baseKey);
  {  // tell the editor page its audition key produced sound (frame 83)
    uint8_t pl[5];
    std::memcpy(pl, &reqId, 4);
    pl[4] = 1;
    pageSend(s, 83, pl, sizeof(pl));
  }
}

// Called by the host when an async render failed (e.g. the CDP CLI rejected a parameter):
// the note stays silent; the editor page gets frame 84 with the error message.
extern "C" void cdp_fail(uint32_t reqId, uint32_t msgPtr, uint32_t msgLen) {
  CdpEngine* s = g_current;
  if (!s) return;
  const uint32_t len = std::min(msgLen, 65535u);
  std::vector<uint8_t> pl(6 + len);
  std::memcpy(pl.data(), &reqId, 4);
  const uint16_t l16 = (uint16_t)len;
  std::memcpy(pl.data() + 4, &l16, 2);
  if (len && msgPtr) std::memcpy(pl.data() + 6, (const void*)(uintptr_t)msgPtr, len);
  pageSend(s, 84, pl.data(), pl.size());
  std::printf("cdp-engine: render req=%u failed: %.*s\n", reqId, (int)std::min(msgLen, 200u),
              msgPtr ? (const char*)(uintptr_t)msgPtr : "");
}

