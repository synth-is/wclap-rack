// 4-point cubic Hermite (Catmull-Rom); original implementation, informed by cdp-sampler's
// conventions (see NOTICE) but not copying its LGPL-2.1 header.
inline double cubicHermite(double xm1, double x0, double x1, double x2, double t) {
  const double a = -0.5 * xm1 + 1.5 * x0 - 1.5 * x1 + 0.5 * x2;
  const double b = xm1 - 2.5 * x0 + 2.0 * x1 - 0.5 * x2;
  const double c = -0.5 * xm1 + 0.5 * x1;
  return ((a * t + b) * t + c) * t + x0;
}

struct Voice {
  bool active = false;
  bool hasBuffer = false;
  bool released = false;  // note-off seen before the buffer arrived
  uint64_t age = 0;
  uint32_t reqId = 0;
  int key = 0;
  double velocity = 0;
  float* buf = nullptr;  // owned, channel-major
  uint32_t frames = 0, chans = 0;
  double rate = 48000, step = 1;
  int baseKey = 60;
  double pos = 0;
  double env = 0;
  int stage = 0;  // 0 attack, 1 sustain, 2 release
  uint32_t stageLeft = 0;
  double stageStep = 0;
};

struct PageNote {
  bool on;
  int key;
  double velocity;
  uint16_t reqId;  // page-supplied id, echoed back in frames 83/84 (0 = plugin assigns)
};

struct CdpEngine {
  clap_plugin_t plugin;
  const clap_host_t* host;
  const clap_host_webview_t* hostWebview = nullptr;
  double sampleRate = 48000;
  double volumeDb = kVolDefault;
  double program = 0;
  double duration = kDurDefault;
  double rootKey = 60;
  double p[12];
  bool paramOut[kParamCount];
  std::vector<PageNote> pageNotes;  // audition notes from the editor page (consumed in process)
  std::map<std::string, std::vector<uint8_t>> files;
  uint32_t filesDigest = 0x811c9dc5u;
  Voice voices[kVoiceCount];
  uint64_t voiceCounter = 0;
  uint32_t nextReqId = 0x10000;  // page-supplied reqIds are u16, so MIDI-origin ones start high
  bool active = false;
  bool guiOpen = false;
  CdpEngine() {
    for (auto& v : p) v = kUnset;
    for (auto& o : paramOut) o = false;
  }
};

CdpEngine* self(const clap_plugin_t* p) { return static_cast<CdpEngine*>(p->plugin_data); }

double clampDouble(double v, double lo, double hi) { return std::min(hi, std::max(lo, v)); }

void freeVoiceBuffer(Voice& v) {
  if (v.buf) std::free(v.buf);
  v.buf = nullptr;
  v.hasBuffer = false;
}

// Build the render spec JSON for the current params and issue the bridge request.
void requestRender(CdpEngine* s, Voice& v, int key, double velocity, uint32_t pageReqId = 0) {
  char spec[640];
  int n = std::snprintf(spec, sizeof(spec), "{\"i\":%d,\"dur\":%.6f,\"root\":%d,\"p\":[", (int)s->program,
                        s->duration, (int)s->rootKey);
  for (int i = 0; i < 12 && n > 0 && n < (int)sizeof(spec) - 32; ++i)
    n += std::snprintf(spec + n, sizeof(spec) - n, "%s%.9g", i ? "," : "", s->p[i]);
  if (n > 0 && n < (int)sizeof(spec) - 4) std::snprintf(spec + n, sizeof(spec) - n, "]}");
  v.reqId = pageReqId ? pageReqId : s->nextReqId++;
  v.key = key;
  v.velocity = velocity;
  v.pos = 0;
  v.env = 0;
  v.stage = 0;
  v.stageLeft = 0;
  v.released = false;
  v.hasBuffer = false;
  v.active = true;
  v.age = ++s->voiceCounter;
  const uint32_t ok = cdp_render_request(v.reqId, (uint32_t)(uintptr_t)spec, (uint32_t)std::strlen(spec), key,
                                         (uint32_t)clampDouble(velocity * 127.0, 0, 127));
  if (!ok) {
    std::printf("cdp-engine: host has no wclap.cdp/1 bridge; note %d silent\n", key);
    v.active = false;
  }
}

void noteOn(CdpEngine* s, int key, double velocity, uint32_t pageReqId = 0) {
  Voice* v = nullptr;
  for (auto& c : s->voices)
    if (!c.active) { v = &c; break; }
  if (!v) {  // steal the oldest
    v = &s->voices[0];
    for (auto& c : s->voices)
      if (c.age < v->age) v = &c;
    freeVoiceBuffer(*v);
  }
  requestRender(s, *v, key, velocity, pageReqId);
}

void noteOff(CdpEngine* s, int key) {
  for (auto& v : s->voices) {
    if (!v.active || v.key != key) continue;
    if (!v.hasBuffer) {
      v.released = true;  // release as soon as (if) the buffer arrives
      continue;
    }
    if (v.stage != 2) {
      v.stage = 2;
      const uint32_t dur = (uint32_t)std::max(1.0, kReleaseSec * s->sampleRate);
      v.stageLeft = dur;
      v.stageStep = -v.env / (double)dur;
    }
  }
}

// ── clap.params ────────────────────────────────────────────────────────────────────────────────────────

uint32_t paramsCount(const clap_plugin_t*) { return kParamCount; }

bool paramsInfo(const clap_plugin_t*, uint32_t i, clap_param_info_t* info) {
  if (i >= kParamCount) return false;
  std::memset(info, 0, sizeof(*info));
  info->id = i;
  info->flags = CLAP_PARAM_IS_AUTOMATABLE | CLAP_PARAM_IS_MODULATABLE;
  switch (i) {
    case kParamVolume:
      std::snprintf(info->name, sizeof(info->name), "Volume");
      info->min_value = kVolMin; info->max_value = kVolMax; info->default_value = kVolDefault;
      break;
    case kParamProgram:
      std::snprintf(info->name, sizeof(info->name), "Program (catalog index)");
      info->min_value = 0; info->max_value = 255; info->default_value = 0;
      info->flags |= CLAP_PARAM_IS_STEPPED;
      break;
    case kParamDuration:
      std::snprintf(info->name, sizeof(info->name), "Duration (s)");
      info->min_value = kDurMin; info->max_value = kDurMax; info->default_value = kDurDefault;
      break;
    case kParamRoot:
      std::snprintf(info->name, sizeof(info->name), "Root key");
      info->min_value = 0; info->max_value = 127; info->default_value = 60;
      info->flags |= CLAP_PARAM_IS_STEPPED;
      break;
    default:
      std::snprintf(info->name, sizeof(info->name), "P%d", i - kParamP1 + 1);
      info->min_value = -1e9; info->max_value = 1e9; info->default_value = kUnset;
      break;
  }
  info->module[0] = '\0';
  return true;
}

double paramGet(CdpEngine* s, clap_id id) {
  switch (id) {
    case kParamVolume: return s->volumeDb;
    case kParamProgram: return s->program;
    case kParamDuration: return s->duration;
    case kParamRoot: return s->rootKey;
    default: return id >= kParamP1 && id < kParamCount ? s->p[id - kParamP1] : 0;
  }
}

bool paramsGetValue(const clap_plugin_t* p, clap_id id, double* out) {
  if (id >= kParamCount) return false;
  *out = paramGet(self(p), id);
  return true;
}

void paramSet(CdpEngine* s, clap_id id, double v) {
  switch (id) {
    case kParamVolume: s->volumeDb = clampDouble(v, kVolMin, kVolMax); break;
    case kParamProgram: {
      s->program = clampDouble(std::floor(v + 0.5), 0, 255);
      // P1..P12 are positional per program: values from the previous program are usually
      // out of range for the new one (the CDP CLI rejects them), so reset to catalog
      // defaults and report the reset to the host/editor page as out-events.
      for (int i = 0; i < 12; ++i) {
        s->p[i] = kUnset;
        s->paramOut[kParamP1 + i] = true;
      }
      break;
    }
    case kParamDuration: s->duration = clampDouble(v, kDurMin, kDurMax); break;
    case kParamRoot: s->rootKey = clampDouble(std::floor(v + 0.5), 0, 127); break;
    default:
      if (id >= kParamP1 && id < kParamCount) s->p[id - kParamP1] = v;
      break;
  }
}

bool paramsValueToText(const clap_plugin_t* p, clap_id id, double value, char* out, uint32_t cap) {
  if (id >= kParamCount) return false;
  CdpEngine* s = self(p);
  switch (id) {
    case kParamVolume: std::snprintf(out, cap, "%.1f dB", clampDouble(value, kVolMin, kVolMax)); return true;
    case kParamProgram: std::snprintf(out, cap, "%d", (int)clampDouble(std::floor(value + 0.5), 0, 255)); return true;
    case kParamDuration: std::snprintf(out, cap, "%.2f s", clampDouble(value, kDurMin, kDurMax)); return true;
    case kParamRoot: std::snprintf(out, cap, "%d", (int)clampDouble(std::floor(value + 0.5), 0, 127)); return true;
    default:
      if (value <= kUnset + 1) { std::snprintf(out, cap, "default"); return true; }
      std::snprintf(out, cap, "%.6g", value); return true;
  }
  (void)s;
}

bool paramsTextToValue(const clap_plugin_t*, clap_id id, const char* text, double* out) {
  if (id >= kParamCount) return false;
  char* end = nullptr;
  double v = std::strtod(text, &end);
  if (end == text) return false;
  *out = v;
  return true;
}

void paramsFlush(const clap_plugin_t* p, const clap_input_events_t* in, const clap_output_events_t*) {
  CdpEngine* s = self(p);
  const uint32_t total = in->size(in);
  for (uint32_t i = 0; i < total; ++i) {
    const clap_event_header_t* h = in->get(in, i);
    if (h->space_id != CLAP_CORE_EVENT_SPACE_ID || h->type != CLAP_EVENT_PARAM_VALUE) continue;
    auto* e = reinterpret_cast<const clap_event_param_value_t*>(h);
    if (e->param_id < kParamCount) paramSet(s, e->param_id, e->value);
  }
}

const clap_plugin_params_t kParams = {paramsCount, paramsInfo, paramsGetValue, paramsValueToText, paramsTextToValue,
                                      paramsFlush};

// ── clap.state ─────────────────────────────────────────────────────────────────────────────────────────

bool stateSave(const clap_plugin_t* p, const clap_ostream_t* out) {
  CdpEngine* s = self(p);
  std::vector<unsigned char> buf;
  buf.push_back(kStateVersion);
  double vals[15];
  vals[0] = s->volumeDb; vals[1] = s->program; vals[2] = s->duration; vals[3] = s->rootKey;
  for (int i = 0; i < 12; ++i) vals[4 + i] = s->p[i];
  buf.insert(buf.end(), (unsigned char*)vals, (unsigned char*)vals + sizeof(vals));
  int64_t done = 0;
  while (done < (int64_t)buf.size()) {
    int64_t n = out->write(out, buf.data() + done, buf.size() - done);
    if (n <= 0) return false;
    done += n;
  }
  return true;
}

bool stateLoad(const clap_plugin_t* p, const clap_istream_t* in) {
  std::vector<unsigned char> buf;
  unsigned char chunk[4096];
  for (;;) {
    int64_t n = in->read(in, chunk, sizeof(chunk));
    if (n < 0) return false;
    if (n == 0) break;
    buf.insert(buf.end(), chunk, chunk + n);
  }
  if (buf.size() < 1 + 15 * 8 || buf[0] != kStateVersion) return false;
  double vals[15];
  std::memcpy(vals, buf.data() + 1, sizeof(vals));
  CdpEngine* s = self(p);
  s->volumeDb = clampDouble(vals[0], kVolMin, kVolMax);
  s->program = clampDouble(std::floor(vals[1] + 0.5), 0, 255);
  s->duration = clampDouble(vals[2], kDurMin, kDurMax);
  s->rootKey = clampDouble(std::floor(vals[3] + 0.5), 0, 127);
  for (int i = 0; i < 12; ++i) s->p[i] = vals[4 + i];
  return true;
}

