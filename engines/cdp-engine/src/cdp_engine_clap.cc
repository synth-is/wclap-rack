// Set by createPlugin: the most recently created instance. WCLAP rack hosts run one
// instance per module, so cdp_deliver (which receives no plugin pointer) can find it.
CdpEngine* g_current = nullptr;

const clap_plugin_t* createPlugin(const clap_host_t* host) {
  void* mem = std::calloc(1, sizeof(CdpEngine));
  CdpEngine* s = new (mem) CdpEngine();
  s->host = host;
  g_current = s;
  s->plugin = {&kDescriptor, s, pluginInit, pluginDestroy, pluginActivate, pluginDeactivate, pluginStartProcessing,
               pluginStopProcessing, pluginReset, pluginProcess, pluginGetExtension, pluginOnMainThread};
  return &s->plugin;
}

