// cdp-engine: the CDP-WASM-SUITE (Composer's Desktop Project programs compiled to WASM,
// https://github.com/cdp-wasm-suite) as ONE consolidated WCLAP instrument — the
// Airwindows-Consolidated shape: a "Program" parameter selects among the catalog's
// generator programs (16 curated entries over 9 CDP programs; the full 215-program suite
// is reachable through the same bridge), and each note-on asks the HOST to render the
// program offline via the wclap.cdp/1 bridge, then plays the rendered buffer polyphonically.
//
// Why a host bridge and not CDP wasm inside this module: the cdp-wasm programs are
// Emscripten side modules that need their JS glue (MEMFS + dynamic linking into a shared
// cdp-core), which cannot run inside a standalone wasm module. So the render happens in the
// host's JS (reference-host/cdp-bridge.mjs, or the web app's worklet) using the vendored
// cdp-wasm engine, and the result is handed back here. This mirrors how cdp-plugin itself
// works (render offline with CDP, play back through a polyphonic sampler — cdp-sampler),
// and how our SFZ renditions and CPPN pre-rendered notes work: CDP is an offline toolkit,
// so in a rack it is a source (rendered per note) or an offline stage at extract time.
//
//   * Bridge, module "wclap.cdp/1":
//       import  u32 render_request(u32 reqId, const char* spec, u32 specLen, i32 note, u32 vel7)
//               called synchronously from process() on note-on; the host starts an async
//               render and later calls the exported cdp_deliver. Returns 1 if accepted.
//       export  void cdp_deliver(u32 reqId, float* planar, u32 frames, u32 chans,
//                                double rate, i32 baseKey)
//               the host mallocs `planar` in this module's memory (via _malloc) and this
//               function takes ownership (frees with free()). planar is channel-major:
//       export  void cdp_fail(u32 reqId, const char* msg, u32 msgLen)
//               render failed; the note stays silent and the editor page is notified
//               (webview frame 84).
//               channel c starts at planar + c*frames.
//     spec is a small JSON object: {"i":programIndex,"dur":seconds,"root":midiKey,
//     "p":[p1..p12]} — positional params mapped onto the catalog entry's params by the
//     bridge (engines/cdp-engine/catalog.json, generated by scripts/make-catalog.mjs).
//     If the entry has a "freq" param the bridge renders at the note's own frequency
//     (440 * 2^((note-60)/12)) and delivers baseKey=note; otherwise it renders at the
//     root and the voice pitch-shifts by 2^((key-baseKey)/12).
//   * Playback: fixed pool of 16 voices, 4-point cubic Hermite (Catmull-Rom) interpolation,
//     note 60 = native rate. Attack 5 ms; note-off opens a 80 ms release; a voice whose
//     buffer has not arrived yet stays silent until cdp_deliver lands (render latency),
//     and is released immediately if the note is already off. No allocation in process()
//     beyond the fixed voice pool; buffers arrive via cdp_deliver between process calls.
//   * Params (clap.params): 0 Volume dB [-60..12, 0]; 1 Program [0..255 step 1, 0] (index
//     into the catalog's generators); 2 Duration s [0.1..60, 1.5]; 3 Root key [0..127, 60];
//     4..15 P1..P12 [-1e9..1e9, -1e9 = "use the catalog default"] positional program params.
//   * State: [u8 version][f64 vol][f64 program][f64 dur][f64 root][12 x f64 p].
//   * wclap.files/1 (SPEC §8) frames are accepted on clap.webview/3 and logged with the
//     same FNV-1a digest as sfz-engine (e.g. to deliver catalog.json); no editor page.
//   * clap.latency = 0 (render latency is reported per note by the bridge, not hidden);
//     clap.tail = longest ringing voice remainder.

