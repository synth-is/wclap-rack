uint32_t tailGet(const clap_plugin_t* p) {
  CdpEngine* s = self(p);
  double maxRemain = 0;
  for (auto& v : s->voices) {
    if (!v.active || !v.hasBuffer) continue;
    double remain = (v.frames - v.pos) / v.step;
    if (v.stage == 2) remain = std::min(remain, kReleaseSec * s->sampleRate + 1);
    maxRemain = std::max(maxRemain, remain);
  }
  return (uint32_t)std::min(maxRemain, 30.0 * s->sampleRate);
}
const clap_plugin_tail_t kTail = {tailGet};

