void pluginDestroy(const clap_plugin_t* p) {
  CdpEngine* s = self(p);
  for (auto& v : s->voices) freeVoiceBuffer(v);
  s->~CdpEngine();
  std::free(s);
}

bool pluginActivate(const clap_plugin_t* p, double sampleRate, uint32_t, uint32_t) {
  CdpEngine* s = self(p);
  s->sampleRate = sampleRate > 0 ? sampleRate : 48000;
  for (auto& v : s->voices) {
    v.active = false;
    freeVoiceBuffer(v);
  }
  s->active = true;
  return true;
}
void pluginDeactivate(const clap_plugin_t* p) {
  CdpEngine* s = self(p);
  for (auto& v : s->voices) {
    v.active = false;
    freeVoiceBuffer(v);
  }
  s->active = false;
}
