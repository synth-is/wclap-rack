// ── page protocol (frame: u8 type, u8 flags, u16 reserved, payload; little-endian) ─────────────────────
//   page -> plugin   64 hello            (reply: 80 description, 82 values)
//                    65 set parameter    u32 id, f64 value
//                    66 note             u8 on, u8 key, u16 reqId, f32 velocity (audition keyboard)
//                    69 poll             (reply: 82 values)
//   plugin -> page   80 description      JSON {params:[{id,name,min,max,def}], program, duration, root}
//                    82 values           u32 count, then per parameter f64 value
//                    83 delivered        u32 reqId, u8 ok — a render_request landed (audio playing)
//                    84 failed           u32 reqId, u16 len, utf8 message — render failed (stays silent)
// The page merges the description with ui/catalog.json (program names + per-program param
// labels for P1..P12) which it fetches itself, relative to this page.
void pageSend(CdpEngine* s, uint8_t type, const void* payload, size_t n) {
  if (!s->guiOpen || !s->hostWebview || !s->hostWebview->send) return;
  std::vector<uint8_t> f(4 + n);
  f[0] = type;
  f[1] = 0;
  f[2] = 0;
  f[3] = 0;
  if (n) std::memcpy(f.data() + 4, payload, n);
  s->hostWebview->send(s->host, f.data(), (uint32_t)f.size());
}

void pageSendDescription(CdpEngine* s) {
  char buf[2048];
  int n = std::snprintf(buf, sizeof(buf), "{\"params\":[");
  for (uint32_t i = 0; i < kParamCount && n > 0 && n < (int)sizeof(buf) - 96; ++i) {
    clap_param_info_t info;
    if (!paramsInfo(nullptr, i, &info)) continue;
    n += std::snprintf(buf + n, sizeof(buf) - n, "%s{\"id\":%u,\"name\":\"%s\",\"min\":%.9g,\"max\":%.9g,\"def\":%.9g}",
                       i ? "," : "", i, info.name, info.min_value, info.max_value, info.default_value);
  }
  if (n > 0 && n < (int)sizeof(buf) - 64)
    n += std::snprintf(buf + n, sizeof(buf) - n, "],\"program\":%.9g,\"duration\":%.9g,\"root\":%.9g}", s->program,
                       s->duration, s->rootKey);
  pageSend(s, 80, buf, (size_t)std::max(n, 0));
}

void pageSendValues(CdpEngine* s) {
  std::vector<uint8_t> f(4 + 4 + kParamCount * 8);
  f[0] = 82;
  f[1] = 0;
  f[2] = 0;
  f[3] = 0;
  uint32_t count = kParamCount;
  std::memcpy(f.data() + 4, &count, 4);
  for (uint32_t i = 0; i < kParamCount; ++i) {
    double v = paramGet(s, i);
    std::memcpy(f.data() + 8 + i * 8, &v, 8);
  }
  pageSend(s, 82, f.data() + 4, f.size() - 4);
}

bool pageReceive(CdpEngine* s, uint8_t type, const uint8_t* pl, uint32_t plen) {
  auto rdU32 = [&](uint32_t o) { uint32_t v; std::memcpy(&v, pl + o, 4); return v; };
  switch (type) {
    case 64:  // hello
      pageSendDescription(s);
      pageSendValues(s);
      return true;
    case 65: {  // set parameter
      if (plen < 12) return false;
      const uint32_t id = rdU32(0);
      double v;
      std::memcpy(&v, pl + 4, 8);
      if (id < kParamCount) {
        paramSet(s, id, v);
        s->paramOut[id] = true;
      }
      return true;
    }
    case 66: {  // note (audition); u16 reqId lets the page match 83/84 frames to its keys
      if (plen < 8) return false;
      float vel;
      uint16_t rid;
      std::memcpy(&rid, pl + 2, 2);
      std::memcpy(&vel, pl + 4, 4);
      if (s->pageNotes.size() < 64) s->pageNotes.push_back({pl[0] != 0, (int)pl[1], (double)vel, rid});
      return true;
    }
    case 69:  // poll
      pageSendValues(s);
      return true;
    default:
      return false;
  }
}

bool webviewGetResource(const clap_plugin_t*, const char*, char*, uint32_t, const clap_ostream_t*) { return false; }

bool webviewReceive(const clap_plugin_t* p, const void* buffer, uint32_t size) {
  CdpEngine* s = self(p);
  if (size < 4) return false;
  const uint8_t* b = static_cast<const uint8_t*>(buffer);
  const uint8_t* pl = b + 4;
  const uint32_t plen = size - 4;
  if (b[0] >= 64 && b[0] < 80) return pageReceive(s, b[0], pl, plen);
  auto rd16 = [&](uint32_t o) { return (uint16_t)(pl[o] | (pl[o + 1] << 8)); };
  auto rd32 = [&](uint32_t o) {
    return (uint32_t)pl[o] | ((uint32_t)pl[o + 1] << 8) | ((uint32_t)pl[o + 2] << 16) | ((uint32_t)pl[o + 3] << 24);
  };
  if (b[0] == 241) {
    s->files.clear();
    s->filesDigest = 0x811c9dc5u;
    std::printf("wclap.files/1 clear files=0 digest=%08x\n", s->filesDigest);
    return true;
  }
  if (b[0] != 240 || plen < 6) return false;
  const uint16_t pathLen = rd16(0);
  if (plen < (uint32_t)(2 + pathLen + 4)) return false;
  std::string path(reinterpret_cast<const char*>(pl) + 2, pathLen);
  const uint32_t dataLen = rd32(2 + pathLen);
  if (plen < (uint32_t)(6 + pathLen + dataLen)) return false;
  const uint8_t* data = pl + 6 + pathLen;
  s->files[path] = std::vector<uint8_t>(data, data + dataLen);
  uint32_t h = s->filesDigest;
  for (char c : path) { h ^= (uint8_t)c; h *= 0x01000193u; }
  h ^= 0; h *= 0x01000193u;
  for (uint32_t k = 0; k < dataLen; ++k) { h ^= data[k]; h *= 0x01000193u; }
  s->filesDigest = h;
  std::printf("wclap.files/1 write path=%s bytes=%u files=%u digest=%08x\n", path.c_str(), dataLen,
              (unsigned)s->files.size(), s->filesDigest);
  return true;
}

