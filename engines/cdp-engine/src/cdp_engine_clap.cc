void handleEvent(CdpEngine* s, const clap_event_header_t* h) {
  if (h->space_id != CLAP_CORE_EVENT_SPACE_ID) return;
  if (h->type == CLAP_EVENT_PARAM_VALUE) {
    auto* e = reinterpret_cast<const clap_event_param_value_t*>(h);
    if (e->param_id < kParamCount) paramSet(s, e->param_id, e->value);
  } else if (h->type == CLAP_EVENT_NOTE_ON) {
    auto* e = reinterpret_cast<const clap_event_note_t*>(h);
    noteOn(s, e->key, e->velocity);
  } else if (h->type == CLAP_EVENT_NOTE_OFF) {
    auto* e = reinterpret_cast<const clap_event_note_t*>(h);
    noteOff(s, e->key);
  } else if (h->type == CLAP_EVENT_NOTE_CHOKE) {
    auto* e = reinterpret_cast<const clap_event_note_t*>(h);
    for (auto& v : s->voices)
      if (v.active && v.key == e->key) { v.active = false; freeVoiceBuffer(v); }
  } else if (h->type == CLAP_EVENT_MIDI) {
    auto* e = reinterpret_cast<const clap_event_midi_t*>(h);
    const uint8_t status = e->data[0] & 0xf0;
    if (status == 0x90 && e->data[2] > 0)
      noteOn(s, e->data[1], e->data[2] / 127.0);
    else if (status == 0x80 || (status == 0x90 && e->data[2] == 0))
      noteOff(s, e->data[1]);
  }
}

clap_process_status pluginProcess(const clap_plugin_t* p, const clap_process_t* proc) {
  CdpEngine* s = self(p);
  if (!s->active || proc->audio_outputs_count < 1) return CLAP_PROCESS_ERROR;
  const clap_audio_buffer_t* out = &proc->audio_outputs[0];
  if (!out->data32 || out->channel_count < 1) return CLAP_PROCESS_ERROR;
  const uint32_t frames = proc->frames_count;
  const uint32_t outCh = std::min(out->channel_count, 2u);
  const uint32_t total = proc->in_events ? proc->in_events->size(proc->in_events) : 0;
  uint32_t cursor = 0;
  const double master = std::pow(10.0, s->volumeDb / 20.0);
  // audition notes from the editor page (delivered on the main thread between blocks)
  for (auto& n : s->pageNotes) {
    if (n.on) noteOn(s, n.key, n.velocity, n.reqId);
    else noteOff(s, n.key);
  }
  s->pageNotes.clear();
  for (uint32_t i = 0; i < frames; ++i) {
    if (proc->in_events) {
      while (cursor < total) {
        const clap_event_header_t* h = proc->in_events->get(proc->in_events, cursor);
        if (h->time > i) break;
        ++cursor;
        handleEvent(s, h);
      }
    }
    float accL = 0, accR = 0;
    for (auto& v : s->voices) {
      if (!v.active || !v.hasBuffer) continue;
      if (v.stageLeft > 0) {
        v.env += v.stageStep;
        if (--v.stageLeft == 0) {
          if (v.stage == 0) {
            v.stage = 1;
            v.stageLeft = 0;
            v.env = 1.0;
          } else if (v.stage == 2) {
            v.active = false;
            continue;
          }
        }
      }
      double pos = v.pos;
      if (pos >= v.frames) {
        v.active = false;
        continue;
      }
      uint32_t i0 = (uint32_t)pos;
      if (i0 >= v.frames) i0 = v.frames - 1;
      double fr = pos - i0;
      uint32_t i1 = i0 + 1;
      if (i1 >= v.frames) i1 = v.frames - 1;
      uint32_t im = i0 > 0 ? i0 - 1 : 0;
      const uint32_t ch = std::min(v.chans, 2u);
      const float* c0 = v.buf + (size_t)0 * v.frames;
      const float* c1 = ch > 1 ? v.buf + (size_t)1 * v.frames : c0;
      float l = (float)cubicHermite(c0[im], c0[i0], c0[i1], c0[std::min(i1 + 1, v.frames - 1)], fr);
      float r = ch > 1 ? (float)cubicHermite(c1[im], c1[i0], c1[i1], c1[std::min(i1 + 1, v.frames - 1)], fr) : l;
      const double gain = v.env * v.velocity * v.velocity * master;
      accL += l * (float)gain;
      accR += r * (float)gain;
      v.pos += v.step;
      if (v.pos >= v.frames) v.active = false;
    }
    if (outCh > 0) out->data32[0][i] = accL;
    if (outCh > 1) out->data32[1][i] = accR;
  }
  if (proc->in_events) {
    while (cursor < total) handleEvent(s, proc->in_events->get(proc->in_events, cursor++));
  }
  // parameters moved by the editor page are reported to the host
  if (proc->out_events && proc->out_events->try_push)
    for (uint32_t i = 0; i < kParamCount; i++)
      if (s->paramOut[i]) {
        clap_event_param_value_t ev;
        std::memset(&ev, 0, sizeof(ev));
        ev.header.size = sizeof(ev);
        ev.header.time = frames ? frames - 1 : 0;
        ev.header.space_id = CLAP_CORE_EVENT_SPACE_ID;
        ev.header.type = CLAP_EVENT_PARAM_VALUE;
        ev.param_id = i;
        ev.note_id = -1;
        ev.port_index = -1;
        ev.channel = -1;
        ev.key = -1;
        ev.value = paramGet(s, i);
        proc->out_events->try_push(proc->out_events, &ev.header);
        s->paramOut[i] = false;
      }
  return CLAP_PROCESS_CONTINUE;
}

